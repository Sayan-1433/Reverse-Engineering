# distance to nearest wall align with acceleration shape
x = pos[:, :-1, :, 0]                             # shape (S, T-1, N)
y = pos[:, :-1, :, 1]

# distance to closest wall
dist_wall = np.minimum.reduce([x, 1-x, y, 1-y])   # shape(S, T-1, N)
mask_far_wall = dist_wall > 0.05   # far from walls

# compute pairwise distances to avoid neighbours
S, T1, N, _ = acc.shape
pair_dist = np.zeros((S, T1, N, N))
for i in range(N):
  for j in range(N):
    diff = pos[:, :-1, i, :] - pos[:, :-1, j, :]
    pair_dist[:, :, i, j] = np.linalg.norm(diff, axis=-1)

# far from any neighbour
mask_far_neighbour = pair_dist.min(axis=-1) > 0.02

# thermal mask = mask for wall + mask far neighbour
thermal_mask = mask_far_wall & mask_far_neighbour & (~hit_wall[:, :-1, :])

thermal_acc = acc_mag[thermal_mask]

if thermal_acc.size == 0:
  print("No thermal noise")
else:
  # plotting the figure
  plt.figure(figsize=(8,5))
